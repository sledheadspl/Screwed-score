#!/usr/bin/env python3
"""Build the free public previews for the Quick-Fix lesson pages.

Reads every private/downloads/academy-qf-*.html guide and writes
lib/academy-previews.generated.ts: the intro, "what you'll learn", the step
outline (titles only) and the full text of Step 1, about 20% of each guide.
Safety notes, the tools and parts lists, Steps 2+, troubleshooting, "when to
call a pro" and the checklist stay behind the paywall.

Run from the repo root after changing any lesson:
    python3 -I scripts/academy/build_previews.py
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'private' / 'downloads'
OUT = ROOT / 'lib' / 'academy-previews.generated.ts'


def text(fragment: str) -> str:
    """Strip tags and collapse whitespace."""
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', fragment))).strip()


def items(fragment: str) -> list[str]:
    return [text(li) for li in re.findall(r'<li>(.*?)</li>', fragment, re.S)]


def section_after_h2(body: str, *names: str) -> str | None:
    """Return the HTML from an <h2> with one of the given names up to the end of its container."""
    for name in names:
        m = re.search(r'<h2>' + re.escape(name) + r'</h2>(.*?)</(?:section|div)>', body, re.S)
        if m:
            return m.group(1)
    return None


def parse(path: Path) -> dict:
    raw = path.read_text(encoding='utf-8')
    body = raw.split('<body', 1)[1]

    def one(pattern: str) -> str:
        m = re.search(pattern, body, re.S)
        return text(m.group(1)) if m else ''

    main = body.split('<main', 1)[1]
    intro_section = re.search(r'<section>(.*?)</section>', main, re.S).group(1)
    intro = text(re.search(r'<p>(.*?)</p>', intro_section, re.S).group(1))
    save = re.findall(r'<div class="k">(.*?)</div><div class="v">(.*?)</div>', intro_section, re.S)

    learn = items(section_after_h2(main, "What you'll learn") or '')
    if not learn:
        raise ValueError(f"{path.name}: no \"What you'll learn\" list")

    steps = re.findall(r'<section><h3><span class="mod-num">(.*?)</span>(.*?)</h3>(.*?)</section>', main, re.S)
    if not steps:
        raise ValueError(f'{path.name}: no steps found')
    outline = [{'label': text(label), 'title': text(title)} for label, title, _ in steps]
    first_label, first_title, first_body = steps[0]
    first = {
        'label': text(first_label),
        'title': text(first_title),
        'items': items(first_body),
        'notes': [
            {'kind': kind, 'text': text(note)}
            for kind, note in re.findall(r'<div class="box (tip|warn)">(.*?)</div>', first_body, re.S)
        ],
    }

    full_len = len(text(main))
    free = ' '.join([intro, *learn, *(o['title'] for o in outline),
                     *first['items'], *(n['text'] for n in first['notes'])])

    return {
        'file': path.name,
        'subtitle': one(r'<p class="sub">(.*?)</p>'),
        'time': one(r'Time: <b>(.*?)</b>'),
        'level': one(r'Level: <b>(.*?)</b>'),
        'intro': intro,
        'save': [{'label': text(k), 'value': text(v)} for k, v in save],
        'learn': learn,
        'outline': outline,
        'firstStep': first,
        '_ratio': round(len(free) / full_len, 3),
    }


def main() -> None:
    previews = {}
    ratios = []
    for path in sorted(SRC.glob('academy-qf-*.html')):
        p = parse(path)
        ratios.append((p.pop('_ratio'), path.name))
        previews[p['file']] = p

    OUT.write_text(
        '// GENERATED by scripts/academy/build_previews.py from private/downloads/academy-qf-*.html.\n'
        "// Don't edit by hand: change the lesson and re-run. This is the free, public part of each\n"
        '// guide (about the first 20%) shown on /academy/quick-fix/[slug]. Server-only by convention.\n'
        "import type { LessonPreview } from './academy-previews'\n\n"
        'export const LESSON_PREVIEWS: Record<string, LessonPreview> = '
        + json.dumps(previews, indent=2, ensure_ascii=False) + '\n',
        encoding='utf-8',
    )
    ratios.sort()
    avg = sum(r for r, _ in ratios) / len(ratios)
    print(f'{len(previews)} previews -> {OUT.relative_to(ROOT)}', file=sys.stderr)
    print(f'free share of text: avg {avg:.0%}, min {ratios[0][0]:.0%} ({ratios[0][1]}), '
          f'max {ratios[-1][0]:.0%} ({ratios[-1][1]})', file=sys.stderr)


if __name__ == '__main__':
    main()
